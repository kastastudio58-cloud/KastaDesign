/** Адрес страницы на нужном языке: русская версия без префикса, английская — с /en */
export const localePath = (lang: Lang, path = '/') => {
  const clean = path.startsWith('/') ? path : `/${path}`;
  if (lang === 'ru') return clean;
  return clean === '/' ? '/en/' : `/en${clean}`;
};

